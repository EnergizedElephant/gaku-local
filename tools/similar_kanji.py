"""
Builds app/src/main/assets/similar_kanji.txt from Lars Yencken's kanji confusion data:
https://lars.yencken.org/datasets/kanji-confusion/ (jyouyou__strokeEditDistance.csv, CC BY 3.0).

Each input line is a kanji followed by its 10 most similar jōyō kanji and their similarity, space
separated. The output lists, for each kanji, up to 10 lookalikes from either direction (if A lists B,
B also gets A), most similar first.

Usage: python3 tools/similar_kanji.py jyouyou__strokeEditDistance.csv app/src/main/assets/similar_kanji.txt
"""
import sys
from collections import defaultdict

MAX_NEIGHBOURS = 10

src, dst = sys.argv[1], sys.argv[2]
similarity = defaultdict(dict)
with open(src, encoding="utf-8") as f:
    for line in f:
        fields = line.split()
        if not fields:
            continue
        kanji, rest = fields[0], fields[1:]
        for other, score in zip(rest[0::2], rest[1::2]):
            score = float(score)
            for a, b in ((kanji, other), (other, kanji)):
                similarity[a][b] = max(score, similarity[a].get(b, 0.0))

with open(dst, "w", encoding="utf-8") as f:
    f.write("# Visually similar kanji, most similar first. Generated by tools/similar_kanji.py from\n")
    f.write("# Lars Yencken's kanji confusion data (stroke edit distance, Yencken & Baldwin 2008),\n")
    f.write("# https://lars.yencken.org/datasets/kanji-confusion/, licensed CC BY 3.0.\n")
    for kanji in sorted(similarity):
        neighbours = sorted(similarity[kanji].items(), key=lambda kv: (-kv[1], kv[0]))[:MAX_NEIGHBOURS]
        f.write(kanji + " " + "".join(k for k, _ in neighbours) + "\n")
